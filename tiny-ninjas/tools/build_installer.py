"""Packs the game into studio/install.luau, a single ModuleScript that installs it into
the place open in Roblox Studio when run from the Command Bar (see README.md).

Run from the tiny-ninjas folder:  python3 tools/build_installer.py
It asks Rojo for the instance tree, so it always matches default.project.json.
"""
import hashlib
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "studio", "install.luau")

# Containers that already exist in every place; everything mounted under them is ours.
EXISTING = {"StarterPlayerScripts", "StarterCharacterScripts"}
# Project properties Studio no longer lets anyone change.
SKIP_PROPERTIES = {"FilteringEnabled", "RespectFilteringEnabled"}


def long_string(text):
    level = 0
    while "]" + "=" * level + "]" in text:
        level += 1
    eq = "=" * level
    return f"[{eq}[\n{text}]{eq}]"


def lua_value(prop, value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return f"Enum.{prop}.{value}"
    if isinstance(value, list) and len(value) == 3:
        return "Color3.new({}, {}, {})".format(*value)
    raise ValueError(f"Don't know how to write {prop} = {value!r}")


def main():
    sourcemap = json.loads(subprocess.check_output(["rojo", "sourcemap", "default.project.json"], cwd=ROOT))
    project = json.load(open(os.path.join(ROOT, "default.project.json")))

    sources = []

    def script_node(node, depth):
        pad = "\t" * depth
        fields = [f"name = {json.dumps(node['name'])}", f"className = {json.dumps(node['className'])}"]
        files = [p for p in node.get("filePaths", []) if p.endswith((".luau", ".lua"))]
        if files:
            text = open(os.path.join(ROOT, files[0])).read()
            sources.append(text)
            fields.append(f"source = {len(sources)}")
        children = node.get("children", [])
        if children:
            inner = ",\n".join(script_node(c, depth + 1) for c in children)
            fields.append("children = {\n" + inner + ",\n" + pad + "}")
        return pad + "{ " + ", ".join(fields) + " }"

    mounts = []

    def find_mounts(node, path):
        for child in node.get("children", []):
            if not path or child["name"] in EXISTING:
                find_mounts(child, path + [child["name"]])
            else:
                mounts.append((path, child))

    find_mounts(sourcemap, [])

    mount_lines = []
    for path, node in mounts:
        mount_lines.append("\t{ parent = { " + ", ".join(json.dumps(p) for p in path) + " }, node =\n"
                           + script_node(node, 2) + " },")

    prop_lines = []
    for service, spec in project["tree"].items():
        if not isinstance(spec, dict):
            continue
        for prop, value in spec.get("$properties", {}).items():
            if prop in SKIP_PROPERTIES:
                continue
            prop_lines.append(f'\t{{ {json.dumps(service)}, {json.dumps(prop)}, function() return {lua_value(prop, value)} end }},')

    build = hashlib.sha1("\0".join(sources).encode()).hexdigest()[:8]
    source_lines = [f"\t{long_string(s)}," for s in sources]

    out = f'''-- Tiny Ninjas installer. GENERATED by tools/build_installer.py, do not edit by hand.
-- Studio's Command Bar downloads this file and runs it (the command is in README.md).
-- It replaces the game's scripts in the open place with this version.

local BUILD = "{build}"

local SOURCES = {{
{chr(10).join(source_lines)}
}}

-- Where each script tree goes: a path of existing containers, then the tree itself.
local MOUNTS = {{
{chr(10).join(mount_lines)}
}}

-- Place settings from default.project.json.
local PROPERTIES = {{
{chr(10).join(prop_lines)}
}}

local function create(node, parent)
	local instance = Instance.new(node.className)
	instance.Name = node.name
	if node.source then
		(instance :: any).Source = SOURCES[node.source]
	end
	for _, child in node.children or {{}} do
		create(child, instance)
	end
	instance.Parent = parent
	return instance
end

return function()
	for _, mount in MOUNTS do
		local parent: Instance = game:GetService(mount.parent[1])
		for i = 2, #mount.parent do
			parent = parent:WaitForChild(mount.parent[i])
		end
		local old = parent:FindFirstChild(mount.node.name)
		if old then
			old:Destroy()
		end
		create(mount.node, parent)
	end

	for _, entry in PROPERTIES do
		local ok, err = pcall(function()
			(game:GetService(entry[1]) :: any)[entry[2]] = entry[3]()
		end)
		if not ok then
			warn(`Tiny Ninjas: could not set {{entry[1]}}.{{entry[2]}}: {{err}}`)
		end
	end

	-- Studio templates add haze and glow effects that would tint the flat grey look.
	local Lighting = game:GetService("Lighting")
	for _, child in Lighting:GetChildren() do
		if child:IsA("Atmosphere") or child:IsA("PostEffect") then
			child:Destroy()
		end
	end

	-- The game itself never uses HTTP; the install command turns it on again when needed.
	game:GetService("HttpService").HttpEnabled = false

	print(`Tiny Ninjas installed (build {{BUILD}}, {{#SOURCES}} scripts). Press Play to test, then File > Save.`)
end
'''
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(out)
    print(f"Wrote {os.path.relpath(OUT, ROOT)}: {len(sources)} scripts, build {build}, {len(out)} bytes")


if __name__ == "__main__":
    main()
