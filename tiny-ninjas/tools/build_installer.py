"""Writes studio/install.luau: a small ModuleScript that installs the game into the place
open in Roblox Studio when run from the Command Bar (see README.md).

The installer holds the instance tree (from Rojo, so it always matches default.project.json)
and downloads every script's source from GitHub at the commit given to it, so it stays
small however big the game gets. Run from the tiny-ninjas folder:

    python3 tools/build_installer.py
"""
import hashlib
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "studio", "install.luau")
REPO = "will51mps0n/Adam-Simpson-Portfolio"
FOLDER = "tiny-ninjas"

# Containers that already exist in every place; everything mounted under them is ours.
EXISTING = {"StarterPlayerScripts", "StarterCharacterScripts"}
# Project properties Studio no longer lets anyone change.
SKIP_PROPERTIES = {"FilteringEnabled", "RespectFilteringEnabled"}


def lua_value(prop, value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return f"Enum.{prop}.{value}"
    if isinstance(value, list) and len(value) == 3:
        return "Color3.new({}, {}, {})".format(*value)
    raise ValueError(f"Don't know how to write {prop} = {value!r}")


def main():
    sourcemap = json.loads(subprocess.check_output(["rojo", "sourcemap", "default.project.json"], cwd=ROOT))
    project = json.load(open(os.path.join(ROOT, "default.project.json")))

    digest = hashlib.sha1()
    count = 0

    def script_node(node, depth):
        nonlocal count
        pad = "\t" * depth
        fields = [f"name = {json.dumps(node['name'])}", f"className = {json.dumps(node['className'])}"]
        files = [p for p in node.get("filePaths", []) if p.endswith((".luau", ".lua"))]
        if files:
            path = files[0].replace(os.sep, "/")
            digest.update(open(os.path.join(ROOT, path), "rb").read())
            count += 1
            fields.append(f"path = {json.dumps(path)}")
        children = node.get("children", [])
        if children:
            inner = ",\n".join(script_node(c, depth + 1) for c in children)
            fields.append("children = {\n" + inner + ",\n" + pad + "}")
        return pad + "{ " + ", ".join(fields) + " }"

    mounts = []

    def find_mounts(node, path):
        for child in node.get("children", []):
            if not path or child["name"] in EXISTING:
                find_mounts(child, path + [child["name"]])
            else:
                mounts.append((path, child))

    find_mounts(sourcemap, [])
    mount_lines = []
    for path, node in mounts:
        mount_lines.append("\t{ parent = { " + ", ".join(json.dumps(p) for p in path) + " }, node =\n" + script_node(node, 2) + " },")

    prop_lines = []
    for service, spec in project["tree"].items():
        if not isinstance(spec, dict):
            continue
        for prop, value in spec.get("$properties", {}).items():
            if prop in SKIP_PROPERTIES:
                continue
            prop_lines.append(f'\t{{ {json.dumps(service)}, {json.dumps(prop)}, function() return {lua_value(prop, value)} end }},')

    build = digest.hexdigest()[:8]
    nl = "\n"
    out = f'''-- Tiny Ninjas installer. GENERATED by tools/build_installer.py, do not edit by hand.
-- Studio's Command Bar downloads this file and runs it with a commit id (the command is
-- in README.md). It downloads every script at that commit, then replaces the game's
-- scripts in the open place with them.

local BUILD = "{build}"
local REPO = "{REPO}"
local FOLDER = "{FOLDER}"

-- Where each script tree goes: a path of existing containers, then the tree itself.
local MOUNTS = {{
{nl.join(mount_lines)}
}}

-- Place settings from default.project.json.
local PROPERTIES = {{
{nl.join(prop_lines)}
}}

local HttpService = game:GetService("HttpService")

local function download(node, base: string, sources: {{ [string]: string }})
	if node.path then
		local ok, result = pcall(function()
			return HttpService:GetAsync(base .. node.path, true)
		end)
		if not ok then
			error(`Tiny Ninjas: couldn't download {{node.path}}: {{result}}`, 0)
		end
		sources[node.path] = result
	end
	for _, child in node.children or {{}} do
		download(child, base, sources)
	end
end

local function create(node, parent: Instance, sources: {{ [string]: string }})
	local instance = Instance.new(node.className)
	instance.Name = node.name
	if node.path then
		(instance :: any).Source = sources[node.path]
	end
	for _, child in node.children or {{}} do
		create(child, instance, sources)
	end
	instance.Parent = parent
end

return function(commit: string?)
	if type(commit) ~= "string" or commit == "" then
		error("Tiny Ninjas: use the install command from README.md (it passes the commit to install)", 0)
	end
	local base = `https://raw.githubusercontent.com/{{REPO}}/{{commit}}/{{FOLDER}}/`

	-- Download everything first, so a network hiccup never leaves a half-installed place.
	local sources: {{ [string]: string }} = {{}}
	for _, mount in MOUNTS do
		download(mount.node, base, sources)
	end
	local count = 0
	for _ in sources do
		count += 1
	end

	for _, mount in MOUNTS do
		local parent: Instance = game:GetService(mount.parent[1])
		for i = 2, #mount.parent do
			parent = parent:WaitForChild(mount.parent[i])
		end
		local old = parent:FindFirstChild(mount.node.name)
		if old then
			old:Destroy()
		end
		create(mount.node, parent, sources)
	end

	for _, entry in PROPERTIES do
		local ok, err = pcall(function()
			(game:GetService(entry[1]) :: any)[entry[2]] = entry[3]()
		end)
		if not ok then
			warn(`Tiny Ninjas: could not set {{entry[1]}}.{{entry[2]}}: {{err}}`)
		end
	end

	-- Studio templates add haze and glow effects that would tint the flat grey look.
	for _, child in game:GetService("Lighting"):GetChildren() do
		if child:IsA("Atmosphere") or child:IsA("PostEffect") then
			child:Destroy()
		end
	end

	-- The game itself never uses HTTP; the install command turns it on again when needed.
	HttpService.HttpEnabled = false

	print(`Tiny Ninjas installed (build {{BUILD}}, {{count}} scripts, commit {{string.sub(commit, 1, 7)}}). Press Play to test, then File > Save.`)
end
'''
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(out)
    print(f"Wrote {os.path.relpath(OUT, ROOT)}: {count} scripts, build {build}, {len(out)} bytes")


if __name__ == "__main__":
    main()
